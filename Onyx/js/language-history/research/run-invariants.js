import assert from 'node:assert/strict';
import { LANGUAGE_RESEARCH, auditRootAgeCriteria } from './index.js';
import { inspectNormalization, codePoints, graphemeCount, normalizeText } from './unicode-tools.js';
import { compareProfiles } from './comparison.js';
import { validateResearchProfiles } from './validate.js';

const report = validateResearchProfiles();
assert.equal(report.ok, true, report.errors.join('\n'));
assert.equal(report.profileCount, 5);
const ageAudit = auditRootAgeCriteria(LANGUAGE_RESEARCH);
assert.equal(ageAudit.ok, true, ageAudit.errors.join('\n'));
assert.equal(ageAudit.results.length, 5);
assert.deepEqual(new Set(Object.values(LANGUAGE_RESEARCH).map(p => p.category)), new Set(['Romance', 'Oceanic', 'Asian / Sinitic', 'African', 'Middle Eastern']));
assert.equal(codePoints('ñ')[0].codePoint, 'U+00F1');
assert.equal(codePoints('ְ')[0].nameHint, 'combining-mark');
assert.equal(codePoints('̣')[0].nameHint, 'combining-mark');
assert.equal(inspectNormalization('ñ').nfc, 'ñ');
assert.equal(inspectNormalization('ẹ́').nfc, 'ẹ́');
assert.equal(normalizeText('ẹ́', 'NFD'), 'ẹ́');
assert.equal(graphemeCount('ẹ́'), 1);
assert.equal(graphemeCount('ẹ́'), 1);
assert.equal(LANGUAGE_RESEARCH.fijian.orthography.script.unicodeExamples.find(x => x.text === 'q').points[0], 'U+0071');
assert.equal(LANGUAGE_RESEARCH.hebrew.orthography.script.unicodeExamples.find(x => x.text === 'שׁ').points[1], 'U+05C1');
assert.equal(LANGUAGE_RESEARCH.mandarin.siblings.length >= 8, true);
assert.match(LANGUAGE_RESEARCH.yoruba.rootEvidence.confidence, /low/);
assert.match(LANGUAGE_RESEARCH.yoruba.orthography.script.toneMarkConventions.researchProposal.status, /not part of the standard/);
assert.match(compareProfiles(LANGUAGE_RESEARCH.spanish, LANGUAGE_RESEARCH.hebrew).comparisonLimit, /do not infer family relationship/);
const unicodeExampleCount = Object.values(LANGUAGE_RESEARCH).reduce((n, profile) => n + profile.orthography.script.unicodeExamples.length, 0);
console.log(JSON.stringify({ ok: true, profiles: report.profileCount, rootAgeProfiles: ageAudit.profileCount, unicodeExamples: unicodeExampleCount, errors: [] }, null, 2));
